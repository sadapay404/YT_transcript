/* ═══════════════════════════ 5. SETTINGS / THEMING ═════════════════════════ */

export type ThemeId = "oled" | "cyberpunk" | "glass" | "zen";

/** Drives native `color-scheme` so scrollbars/inputs match the theme. */
export type ColorScheme = "dark" | "light";

export interface ThemeDefinition {
  id: ThemeId;
  label: string;
  tagline: string;
  /** A second line of product-facing detail for the full theme gallery. */
  detail: string;
  /** Optional caution displayed as a distinct badge in the full gallery. */
  warning?: string;
  scheme: ColorScheme;
  /** Three hex swatches for the theme picker preview. */
  swatch: [string, string, string];
  /** Readable text colour on the preview card (swatch[0] background). */
  ink: string;
  /** Featured theme shown as a "signature" card in the picker. */
  signature?: boolean;
}

export type FontFamilyId = "sans" | "serif" | "dyslexic";

export interface FontOption {
  id: FontFamilyId;
  label: string;
  /** Full CSS font stack, injected into `--transcript-font`. */
  stack: string;
  description: string;
  /** The package that self-hosts the face (keeps the app 100% offline-safe). */
  package: string;
}

export interface TypographySettings {
  fontFamily: FontFamilyId;
  /** rem units. */
  fontSize: number;
  lineHeight: number;
  letterSpacing: number;
  /** Max line length in `ch`. */
  measure: number;
}

export type ViewMode = "split" | "cinema" | "read";

export interface ViewModeDefinition {
  id: ViewMode;
  label: string;
  description: string;
}

export interface AppSettings {
  theme: ThemeId;
  typography: TypographySettings;
  viewMode: ViewMode;
  /** Auto-scroll the transcript to follow playback. */
  autoScroll: boolean;
  /** Keep the active sentence vertically centered vs. just visible. */
  centerActiveLine: boolean;
  /** Show (and use) the Gemini assistant panel. */
  sidebarOpen: boolean;
  sidebarWidth: number;
  /** Show offset badges next to transcript lines. */
  showTimestamps: boolean;
  /** Highlight clip bands in the transcript (Step 5). */
  showClipHighlights: boolean;
  /** Honour the OS "reduce motion" preference on top of our animations. */
  reduceMotion: boolean;
}

/* ═══════════════════════════ 6. PLAYER CONTRACT ════════════════════════════ */

export type PlayerStatus = "unstarted" | "playing" | "paused" | "buffering" | "ended";

/** The imperative handle every player implementation must expose. */
export interface PlaybackController {
  seekTo(seconds: number): void;
  play(): void;
  pause(): void;
  toggle(): void;
  getCurrentTime(): number;
  getDuration(): number;
  /** Loop playback between two timestamps (clip preview). */
  setLoopRange(range: ClipRange | null): void;
  setMuted(muted: boolean): void;
  isMuted(): boolean;
}

export interface ClipRange {
  start: number;
  end: number;
  clipId?: string;
}

/** Snapshot of playback, published by the player and consumed by everything. */
export interface PlaybackState {
  status: PlayerStatus;
  currentTime: number;
  duration: number;
  /** Index into `transcript.segments` whose time window contains currentTime. */
  activeSegmentIndex: number;
  playingClipId: string | null;
}

